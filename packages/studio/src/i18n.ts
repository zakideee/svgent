export type Lang = "ja" | "en";

export const LANG_STORAGE_KEY = "lang";

export function initialLang(persistence?: StudioPersistence | null): Lang {
  try {
    const stored = persistence?.getItem(LANG_STORAGE_KEY);
    if (stored === "ja" || stored === "en") {
      return stored;
    }
    return navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
  } catch {
    return "en";
  }
}

